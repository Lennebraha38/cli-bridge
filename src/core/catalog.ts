/** Fast lookup by id and by binary name. */
export const CATALOG_BY_ID = new Map<string, CatalogEntry>(CATALOG.map((entry) => [entry.id.toLowerCase(), entry]));

export const CATALOG_BY_BIN = new Map<string, CatalogEntry[]>();
for (const entry of CATALOG) {
  const key = entry.bin.toLowerCase();
  const list = CATALOG_BY_BIN.get(key) ?? [];
  list.push(entry);
  CATALOG_BY_BIN.set(key, list);
}

/** Catalog entries that can be installed with the given manager id. */
export function catalogByInstallMethod(method: string): CatalogEntry[] {
  return CATALOG.filter((entry) => {
    const spec = entry.install as Record<string, string> | undefined;
    return Boolean(spec && spec[method]);
  });
}
